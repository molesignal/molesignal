//! MoleSignal 服务二进制的构建脚本。
//!
//! 捕获 git commit / branch、CI build ID 与构建时间戳，注入为 rustc-env，供
//! `/version` 接口回显（前端「关于」弹窗 + 状态栏）；同时把预先构建好的 `web/dist`
//! 生成成静态资源表，由 HTTP 入口编译进最终二进制。非 git 环境（如发布 tarball）回退到
//! "unknown"，不影响编译。
//!
//! protobuf 代码生成由 `protocol` 与 `probe-agent` crate 各自的 `build.rs` 负责，产物只写入
//! Cargo `OUT_DIR`。本脚本不运行 pnpm；Makefile、Docker 与 CI 必须先生成前端产物，避免
//! Cargo 构建隐式访问网络或修改源码树。

use std::{
    env,
    ffi::OsStr,
    fmt::Write as _,
    fs, io,
    path::{Path, PathBuf},
    process::Command,
};

const INTERNAL_PRODUCT_VERSION: &str = "26.0.0.0";

fn main() {
    let git = |args: &[&str]| -> String {
        Command::new("git")
            .args(args)
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
            .filter(|s| !s.is_empty())
            .unwrap_or_else(|| "unknown".to_string())
    };
    let commit = env::var("GIT_SHA")
        .ok()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| git(&["rev-parse", "HEAD"]));
    let branch = git(&["rev-parse", "--abbrev-ref", "HEAD"]);
    let build_epoch = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    let build_id = env::var("BUILD_ID")
        .ok()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "unknown".to_string());

    println!("cargo:rustc-env=MOLESIGNAL_GIT_COMMIT={commit}");
    println!("cargo:rustc-env=MOLESIGNAL_GIT_BRANCH={branch}");
    println!("cargo:rustc-env=MOLESIGNAL_BUILD_EPOCH={build_epoch}");
    println!("cargo:rustc-env=MOLESIGNAL_BUILD_ID={build_id}");
    println!("cargo:rustc-env=MOLESIGNAL_PRODUCT_VERSION={INTERNAL_PRODUCT_VERSION}");
    // Best-effort: refresh git info when HEAD moves (ignored if path absent).
    println!("cargo:rerun-if-changed=../../.git/HEAD");
    println!("cargo:rerun-if-env-changed=BUILD_ID");
    println!("cargo:rerun-if-env-changed=GIT_SHA");

    embed_web_assets().unwrap_or_else(|error| panic!("cannot embed MoleSignal Web: {error}"));
}

fn embed_web_assets() -> io::Result<()> {
    let manifest_dir = PathBuf::from(
        env::var_os("CARGO_MANIFEST_DIR")
            .ok_or_else(|| io::Error::other("CARGO_MANIFEST_DIR is not set"))?,
    );
    let dist_dir = manifest_dir.join("../../web/dist");
    let index_path = dist_dir.join("index.html");

    println!("cargo:rerun-if-changed={}", dist_dir.display());

    if !index_path.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!(
                "{} is missing; run `make web-build` before invoking Cargo directly",
                index_path.display()
            ),
        ));
    }

    let mut assets = Vec::new();
    collect_assets(&dist_dir, &dist_dir, &mut assets)?;
    assets.sort_by(|left, right| left.0.cmp(&right.0));
    if !assets.iter().any(|(path, _)| path == "index.html") {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "web/dist does not contain index.html",
        ));
    }

    let mut generated = String::from(
        "// @generated by bin/molesignal/build.rs; DO NOT EDIT.\n\
         static EMBEDDED_WEB_ASSETS: &[EmbeddedWebAsset] = &[\n",
    );
    for (path, absolute_path) in assets {
        writeln!(
            generated,
            "    EmbeddedWebAsset {{ path: {path:?}, body: include_bytes!({absolute_path:?}), content_type: {:?} }},",
            content_type(&path),
            absolute_path = absolute_path.to_string_lossy(),
        )
        .expect("writing to String cannot fail");
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(
        env::var_os("OUT_DIR").ok_or_else(|| io::Error::other("OUT_DIR is not set"))?,
    );
    fs::write(out_dir.join("embedded_web_assets.rs"), generated)
}

fn collect_assets(
    dist_dir: &Path,
    current_dir: &Path,
    assets: &mut Vec<(String, PathBuf)>,
) -> io::Result<()> {
    for entry in fs::read_dir(current_dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect_assets(dist_dir, &path, assets)?;
            continue;
        }
        // Source maps are deployment diagnostics, not runtime UI assets. Keeping them out of the
        // executable avoids inflating the release binary by roughly three times the actual app.
        if path.extension() == Some(OsStr::new("map")) {
            continue;
        }
        let relative = path
            .strip_prefix(dist_dir)
            .map_err(|error| io::Error::other(error.to_string()))?
            .to_string_lossy()
            .replace('\\', "/");
        assets.push((relative, path.canonicalize()?));
    }
    Ok(())
}

fn content_type(path: &str) -> &'static str {
    match Path::new(path).extension().and_then(OsStr::to_str) {
        Some("html") => "text/html; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("json") => "application/json; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("ico") => "image/x-icon",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("webp") => "image/webp",
        Some("woff") => "font/woff",
        Some("woff2") => "font/woff2",
        Some("ttf") => "font/ttf",
        Some("wasm") => "application/wasm",
        Some("txt") => "text/plain; charset=utf-8",
        Some("xml") => "application/xml; charset=utf-8",
        _ => "application/octet-stream",
    }
}
