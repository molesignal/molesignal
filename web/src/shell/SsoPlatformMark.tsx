const PROTOCOL_ICONS: Record<SsoProviderKind, typeof KeyRound> = {
  oidc: KeyRound,
  oauth2: KeyRound,
  saml: ShieldCheck,
  ldap: FolderTree,
};

export function hasPlatformMark(platform: SsoPlatform): boolean {
  return platform in MARKS;
}

export function SsoPlatformMark({
  platform,
  kind,
  size = 16,
  className,
}: {
  platform: SsoPlatform;
  kind: SsoProviderKind;
  size?: number;
  className?: string;
}) {
  const mark = MARKS[platform];

  if (!mark) {
    const Icon = PROTOCOL_ICONS[kind];
    return (
      <Icon
        size={size}
        aria-hidden
        className={cn('shrink-0 text-tx-2', className)}
      />
    );
  }

  return (
    <svg
      width={size}
      height={size}
      viewBox={mark.viewBox}
      aria-hidden
      className={cn('shrink-0 text-tx-0', className)}
      data-sso-mark={platform}
    >
      {mark.body}
    </svg>
  );
}
