const ACTION_OF = new Map<string, OperationAction>(
  (Object.entries(VERBS) as Array<[OperationAction, readonly string[]]>).flatMap(([action, verbs]) =>
    verbs.map((verb) => [verb, action] as const),
  ),
);

/** What a verb does, in any case, or null when it is not one told apart. */
export function operationAction(verb: string): OperationAction | null {
  return ACTION_OF.get(verb.toUpperCase()) ?? null;
}
