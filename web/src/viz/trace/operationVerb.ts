/**
 * What the leading word of a span name does: an HTTP method, a SQL
 * statement, a Redis command or a MongoDB command reads, adds, changes or
 * removes data, or steers the conversation (a transaction, a probe).
 */
export type OperationAction = 'read' | 'add' | 'change' | 'remove' | 'control' | 'other';

/** The ink tones: a verb reads at AA on a row at rest, under the pointer and selected. */
export const OPERATION_TONE: Record<OperationAction, string> = {
  read: 'text-[var(--green-ink)]',
  add: 'text-[var(--blue-ink)]',
  change: 'text-[var(--orange-ink)]',
  remove: 'text-[var(--red-ink)]',
  control: 'text-[var(--purple-ink)]',
  other: 'text-[var(--yellow-ink)]',
};

