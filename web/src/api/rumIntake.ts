import axios from 'axios';

import type { IntakeResult } from '@/api/intake';
import { isMissingStreamError } from '@/api/missingStream';
import * as rumApi from '@/api/rum';

export type RumPlatform = 'browser' | 'flutter' | 'android' | 'ios';

export interface TestRumEventRequest {
  token: string;
  applicationId: string;
  platform: RumPlatform;
  service: string;
}

export interface RumReceiptSummary {
  rows: number;
  lastReceivedAt: number | null;
  /** The streams the rows are in. */
  streams: string[];
}

/**
 * Asks about the kind of a session and leaves it open: what an application has sent counts whoever
 * ran it, and a read is otherwise of real users only.
 */
const EVERY_KIND_OF_SESSION: rumApi.RumFilter = { field: 'session.type', op: 'not_in', value: JSON.stringify(['']) };

/** How far back what an application has sent is looked for. */
const RECEIPT_WINDOW_MICROS = 60 * 60 * 1_000_000;

/**
 * The most rows a receipt counts of one type. A count here is a sign that data arrived, not a
 * measure of how much.
 */
const RECEIPT_ROWS = 100;

/**
 * One visit that did not happen: a view and an error in a session of the synthetic kind, in the
 * shape the intake takes (`contracts/rum/events`). Its session type and its version mark it as a
 * test, so it counts in no figure of the application, and the explorer lists it when asked about
 * the kind of session.
 */
export function testEvents(request: TestRumEventRequest, now = Date.now()) {
  const common = {
    date: now,
    source: request.platform,
    service: request.service,
    env: 'datasource-test',
    version: 'datasource-test',
    application: { id: request.applicationId },
    session: { id: crypto.randomUUID(), type: 'synthetics', start: now },
    sdk: { name: `molesignal-${request.platform}-datasource`, version: '1' },
  };
  const view = {
    id: crypto.randomUUID(),
    url: '/datasource-test',
    name: 'MoleSignal datasource test',
  };

  return [
    {
      type: 'view',
      ...common,
      view: { ...view, revision: 1, time_spent: 1_000_000_000, is_active: false },
    },
    {
      type: 'error',
      ...common,
      view,
      error: {
        id: crypto.randomUUID(),
        message: 'Test error generated by the MoleSignal datasource guide',
        source: 'custom',
        type: 'DatasourceTestError',
        handling: 'handled',
      },
    },
  ];
}

/** What the intake answers: the events it kept, and each one it refused with the reason. */
interface RumIntakeAnswer {
  accepted: number;
  rejected: Array<{ index: number; reason: string }>;
}

export async function sendTestEvents(request: TestRumEventRequest): Promise<IntakeResult> {
  const { data } = await axios.post<RumIntakeAnswer>('/api/v1/rum/events', testEvents(request), {
    headers: { Authorization: `Bearer ${request.token}` },
  });

  return { accepted: data.accepted, rejected: data.rejected.length, errors: data.rejected };
}

/**
 * What an application has sent in the last hour: its views, which every SDK sends as soon as it
 * starts, and its errors, which the test event is one of.
 */
export async function recentReceipt(params: { applicationId: string }): Promise<RumReceiptSummary> {
  const now = Date.now() * 1_000;
  const asked = async (type: 'views' | 'errors', column: string) => {
    try {
      const page = await rumApi.search({
        type,
        from: now - RECEIPT_WINDOW_MICROS,
        to: now,
        limit: RECEIPT_ROWS,
        columns: [column],
        filters: [{ field: 'application.id', op: '=', value: params.applicationId }, EVERY_KIND_OF_SESSION],
      });

      // Newest first: the first row is the last one received.
      return { stream: `rum_${type}`, rows: page.items.length, last: page.items[0]?.timestamp ?? null };
    } catch (error) {
      if (isMissingStreamError(error)) return { stream: `rum_${type}`, rows: 0, last: null };
      throw error;
    }
  };

  const found = await Promise.all([asked('views', 'view.id'), asked('errors', 'error.id')]);
  const arrived = found.filter((item) => item.rows > 0);

  return {
    rows: arrived.reduce((total, item) => total + item.rows, 0),
    lastReceivedAt: arrived.reduce<number | null>(
      (latest, item) => (item.last !== null && (latest === null || item.last > latest) ? item.last : latest),
      null,
    ),
    streams: arrived.map((item) => item.stream),
  };
}
